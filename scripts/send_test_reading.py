def interactive_menu(url, device_id):
    while True:
        print("\n=======================================================")
        print("  CareSense IoE — Smart Telemetry Demo & Test Console  ")
        print(f"  Target URL: {url}")
        print(f"  Target Node: {device_id} (Rahul Sharma • Bed PT-0142)")
        print("=======================================================")
        print("  1) Normal Vitals (HR 74, SpO2 98%, Temp 36.6°C)")
        print("  2) Single Breach (HR 126 BPM -> WATCH state)")
        print("  3) Three Consecutive Breaches (HR+SpO2 breaches -> CRITICAL escalation)")
        print("  4) Emergency SOS Button (Immediate Code Blue emergency modal)")
        print("  5) Patient Fall Detected (MPU-6050 >2.5G impact alert)")
        print("  6) No Finger Contact (IR < 50000 -> null vitals, no false alarm)")
        print("  q) Exit")
        print("-------------------------------------------------------")
        choice = input("Select an option [1-6, q]: ").strip().lower()

        if choice == "1":
            scenario_normal(url, device_id)
        elif choice == "2":
            scenario_single_breach(url, device_id)
        elif choice == "3":
            scenario_three_breaches(url, device_id)
        elif choice == "4":
            scenario_sos(url, device_id)
        elif choice == "5":
            scenario_fall(url, device_id)
        elif choice == "6":
            scenario_no_finger(url, device_id)
        elif choice in ("q", "quit", "exit"):
            print("\nExiting test utility.")
            break
        else:
            print("\nInvalid selection. Please choose 1-6 or q.")


def main():
    parser = argparse.ArgumentParser(description="Healthcare-IoE Telemetry Test Packet Generator")
    parser.add_argument(
        "--scenario",
        choices=["normal", "breach", "3_breaches", "sos", "fall", "no_finger"],
        help="Specific test scenario to execute automatically",
    )
    parser.add_argument(
        "--url",
        default=DEFAULT_URL,
        help=f"Target ingestion endpoint (default: {DEFAULT_URL})",
    )
    parser.add_argument(
        "--device-id",
        default=DEFAULT_DEVICE_ID,
        help=f"ESP32 hardware device identifier (default: {DEFAULT_DEVICE_ID})",
    )

    args = parser.parse_args()

    if args.scenario == "normal":
        scenario_normal(args.url, args.device_id)
    elif args.scenario == "breach":
        scenario_single_breach(args.url, args.device_id)
    elif args.scenario == "3_breaches":
        scenario_three_breaches(args.url, args.device_id)
    elif args.scenario == "sos":
        scenario_sos(args.url, args.device_id)
    elif args.scenario == "fall":
        scenario_fall(args.url, args.device_id)
    elif args.scenario == "no_finger":
        scenario_no_finger(args.url, args.device_id)
    else:
        interactive_menu(args.url, args.device_id)


if __name__ == "__main__":
    main()
